// Four reviewed slides; keep the course order, notebook anchors and task IDs.
export const pilotSlideIds = [
  's07-01-quality-and-failures-s037',
  's07-01-quality-and-failures-s093',
  's08-03-encryption-and-security-testing-s026',
  's08-03-encryption-and-security-testing-s045',
]

export function applyFourSlidePilot(course, bank, pack) {
  const find = id => {
    const slide = course.lectures.flatMap(lecture => lecture.slides).find(slide => slide.id === id)
    if (!slide) throw new Error(`Missing pilot slide: ${id}`)
    return slide
  }
  const note = (id, script, questions, answer) => {
    const previous = pack.notes[id]
    pack.notes[id] = { ...previous, script, questions, answer,
      estimatedSeconds: Math.round(script.trim().split(/\s+/).length / 2.1 + (find(id).task ? 60 : 15)) }
  }

  const tree = find(pilotSlideIds[0])
  tree.title = 'От свойства — к измерению и свидетельству'
  tree.visual = { type: 'tree', root: 'Качество сервиса', branches: [
    { title: 'Надёжность', items: ['Доля времени → журнал', 'Возврат, ч → журнал'] },
    { title: 'Корректность', items: ['Сумма → эталон', 'Запись → тот же ID'] },
  ], caption: 'Каждому свойству — своё измерение и свидетельство. Учебная схема, не полная модель стандарта.' }
  note(tree.id,
    'Прочитайте дерево сверху вниз: качество сервиса раскрываем через отдельные свойства, измерения и свидетельства. Слева показана надёжность: долю времени работоспособного состояния и время возврата функции определяют по журналу состояний и отказов за заданный период. Справа показана корректность: рассчитанную сумму сверяют с эталоном, сохранение заявки — с записью с тем же идентификатором.\n\nЭто четыре разных проверки. Быстрый ответ не подтверждает сохранение, а доступность сервиса не доказывает правильность суммы. Попросите выбрать свидетельство для одного свойства и объяснить границу вывода. Схема учебная и не перечисляет все характеристики модели качества.',
    'Какое свидетельство нужно для проверки суммы? Подойдёт ли для этого журнал доступности?',
    'Нужен эталонный расчёт и сравнение результатов. Журнал доступности подтверждает состояние функции во времени, но не правильность вычисления.')

  const bars = find(pilotSlideIds[1])
  bars.title = 'Сравниваем долю неуспешных операций, %'
  delete bars.body
  delete bars.bullets
  bars.visual = { type: 'bars', max: 4, unit: '', items: [
    { label: 'Период А', value: 2.5 }, { label: 'Период Б', value: 1 },
  ], caption: 'А: 5 из 200; Б: 8 из 800. Один отказ здесь — одна неуспешная операция. Причина изменения не установлена.' }
  note(bars.id,
    'Сравните две вымышленные учебные выборки. Единица учёта — операция; повторные сообщения одной операции уже объединены. В этом примере одному учтённому отказу соответствует одна неуспешная операция. В периоде А их пять из двухсот, в периоде Б — восемь из восьмисот.\n\nВычислите доли: 5 / 200 × 100 = 2,5%; 8 / 800 × 100 = 1,0%. Оба столбца используют одну шкалу от нуля, в процентах. Число неуспешных операций выросло, а доля снизилась. Это описание двух выборок; оно не доказывает причину изменения и не позволяет приписать эффект исправлению без проверки условий и состава нагрузки.',
    'Почему восемь неуспешных операций могут означать меньшую долю, чем пять? Доказывает ли график эффект исправления?',
    'У выборок разные знаменатели: 8/800 = 1%, а 5/200 = 2,5%. Причина изменения не установлена: нужны сопоставимые условия, нагрузка и отдельная проверка гипотезы.')

  const encryption = find(pilotSlideIds[2])
  encryption.title = 'Хранение, канал и копия: три границы защиты'
  encryption.visual = { type: 'network', nodes: [
    { id: 'sender', title: 'Том отправителя', text: 'BitLocker: хранение' },
    { id: 'channel', title: 'TLS-канал', text: 'TLS: обмен между приложениями' },
    { id: 'receiver', title: 'Копия получателя', text: 'Отдельная защита' },
  ], edges: [
    { from: 'sender', to: 'channel', label: 'передача' },
    { from: 'channel', to: 'receiver', label: 'сохранение' },
  ], caption: 'TLS защищает канал. Шифрование сохранённой копии и доступ к данным проверяют отдельно.' }
  note(encryption.id,
    'Покажите три зоны. BitLocker защищает данные на заблокированном томе отправителя; наличие TLS об этом не свидетельствует. TLS защищает обмен между приложениями: проверяют сертификат, имя узла и установленный сеанс. Приложения получают доступ к расшифрованным данным. Копия, сохранённая у получателя, требует отдельной защиты его тома или файла.\n\nСтрелки обозначают передачу и сохранение данных. Они не изображают единственный сквозной ключ или последовательность доказательства. Для каждой зоны назовите собственное свидетельство: состояние тома и проверка разблокировки; параметры и проверка TLS-сеанса; защита сохранённой копии. Отказ ACL — отдельная проверка полномочий, не доказательство шифрования.',
    'Доказывает ли установленный TLS-сеанс шифрование файла на диске получателя?',
    'Нет. Сеанс подтверждает свойства канала в проверенных условиях. Шифрование сохранённой копии и её доступность конкретным ролям проверяют отдельно.')

  const assessment = find(pilotSlideIds[3])
  assessment.title = 'Различите роли в защищённом обмене'
  assessment.task = { id: assessment.task.id, type: 'multiple', choose: 2,
    prompt: 'TLS 1.3, AES-128-GCM, ключ сеанса и TLS-клиент. Выберите два верных утверждения.',
    options: [
      { id: 'o1', text: 'TLS 1.3 задаёт протокол защищённого обмена.' },
      { id: 'o2', text: 'Ключ сеанса — секретный параметр; TLS-клиент — программное средство.' },
      { id: 'o3', text: 'AES-128-GCM — название протокола обмена.' },
      { id: 'o4', text: 'Открытый ключ подтверждает владельца без дополнительной проверки.' },
      { id: 'o5', text: 'Название алгоритма доказывает правильность проверки сертификата.' },
    ] }
  bank.keys[assessment.task.id] = { type: 'multiple', correct: ['o1', 'o2'],
    explanation: 'TLS 1.3 — протокол. AES-128-GCM — алгоритм аутентифицированного шифрования; ключ сеанса — секретный параметр, а TLS-клиент — конкретное программное средство.',
    optionExplanations: {
      o1: 'Верно: TLS 1.3 задаёт протокольные правила защищённого обмена.',
      o2: 'Верно: ключ является параметром криптографической операции, клиент — реализацией протокола.',
      o3: 'AES-128-GCM — алгоритм AEAD, используемый в TLS; он не заменяет весь протокол.',
      o4: 'Открытость ключа не подтверждает его принадлежность нужному владельцу.',
      o5: 'Название алгоритма не доказывает правильность настроек и проверки сертификата.',
    } }
  note(assessment.id,
    'Предложите выбрать два верных утверждения о технической карте обмена. Не называйте буквы до попытки группы. Попросите объяснить роли TLS 1.3, AES-128-GCM, ключа сеанса и клиентской реализации.\n\nПосле проверки разберите различие протокола, алгоритма, параметра и средства. Отдельно объясните две границы вывода: открытый ключ требует подтверждения принадлежности, а название алгоритма не подтверждает правильную проверку сертификата. Это проверка предметных ролей; классифицировать фразы как «действие» и «критерий» здесь не требуется.',
    'Какие два утверждения верны и почему остальные не следуют из названий компонентов?',
    'Верны o1 и o2. TLS — протокол, ключ — параметр, клиент — программная реализация. AES-128-GCM не является протоколом; открытость ключа не удостоверяет владельца; алгоритм не доказывает корректную проверку сертификата.')
}
